"""Independent exact periods of the Perrin recurrence using integer matrices."""
from math import gcd, isqrt, prod

IDENTITY = ((1, 0, 0), (0, 1, 0), (0, 0, 1))
COMPANION = ((0, 1, 0), (0, 0, 1), (1, 1, 0))
INITIAL = (3, 0, 2)
CURVE = 2**255 - 19
GOLD = 2**64 - 2**32 + 1
LARGE = (CURVE - 1) // 781764
GOLD_LARGE = 167034643597991036904547663171
# Known prime divisors sufficient for Pocklington's criterion, with Bernstein's
# Curve25519 chain from https://cr.yp.to/ecdh/curve25519-20051115.pdf, App. B.
DIVISORS = (2, 3, 5, 17, 257, 65537, 5821, 1039033, 11365102077808483,
            19, 8627, 3852010273, 127, 353, 75707, 8574133, 1919519569386763,
            75445702479781427272750846543864801, LARGE)

def prime(n):
    if n < 2:
        return False
    if n < 4_000_000_000:
        return all(n % d for d in range(2, isqrt(n) + 1))
    remaining = n - 1
    for q in DIVISORS:
        if remaining % q:
            continue
        if not prime(q) or not any(pow(a, n-1, n) == 1 and
                gcd(pow(a, (n-1)//q, n)-1, n) == 1 for a in range(2, 100)):
            return False
        while remaining % q == 0:
            remaining //= q
        if ((n-1)//remaining)**2 > n:
            return True
    return False

def multiply(left, right, p):
    return tuple(tuple(sum(a*b for a,b in zip(row, col)) % p
                       for col in zip(*right)) for row in left)

def power(k, p):
    if k < 0:
        raise ValueError("negative exponent")
    acc, base = IDENTITY, COMPANION
    while k:
        if k & 1:
            acc = multiply(acc, base, p)
        k //= 2
        base = multiply(base, base, p)
    return acc

def snapshot(k, p):
    return tuple(sum(a*b for a,b in zip(row, INITIAL)) % p for row in power(k,p))

def verify(p, factors):
    """Prove exact scalar period using three consecutive values at each index."""
    if not prime(p) or not all(e > 0 and prime(q) for q,e in factors.items()):
        raise ValueError("uncertified prime")
    period = prod(q**e for q,e in factors.items())
    if snapshot(period,p) != INITIAL:
        raise ValueError("claimed period does not return to the initial state")
    witnesses = {q: snapshot(period//q,p) for q in factors}
    if INITIAL in witnesses.values():
        raise ValueError("period has a proper divisor returning to the initial state")
    return witnesses

CURVE_FACTORS = {2: 2, 3: 1, 65147: 1, LARGE: 1}
GOLD_FACTORS = {3: 1, 937: 1, 724723: 1, GOLD_LARGE: 1}
# (residue, index of the subgroup generated by that residue)
ROOTS = (
    (14535863002999908821470556791477736972039661322948065771707477577742314888008, 1),
    (45980055862320150516043228587377395813021437899593394500348496167731510246271, 3),
    (55276170371996136086057199629832775068208885443099103767401610262439304505619, 2),
)

def validate_roots(roots):
    if len(roots) != 3 or len({r for r, _ in roots}) != 3:
        raise ValueError("expected three distinct roots")
    for r, index in roots:
        if not 0 < r < CURVE or (r**3-r-1) % CURVE:
            raise ValueError("invalid cubic root")
        if index < 1 or (CURVE-1) % index:
            raise ValueError("invalid subgroup index")
        order = (CURVE-1)//index
        if pow(r, order, CURVE) != 1 or any(
            order % q == 0 and pow(r, order//q, CURVE) == 1 for q in CURVE_FACTORS
        ):
            raise ValueError("incorrect root order")

def audit():
    if prod(q**e for q,e in CURVE_FACTORS.items()) != CURVE-1:
        raise ValueError("incorrect Curve25519 factorization")
    if prod(q**e for q,e in GOLD_FACTORS.items()) != GOLD**2+GOLD+1:
        raise ValueError("incorrect Goldilocks factorization")
    curve_witnesses = verify(CURVE, CURVE_FACTORS)
    gold_witnesses = verify(GOLD, GOLD_FACTORS)
    validate_roots(ROOTS)
    return {
        "curve25519": {"modulus": CURVE, "exact_period": CURVE-1,
                       "roots_and_subgroup_indices": ROOTS,
                       "proper_divisor_states": curve_witnesses},
        "goldilocks": {"modulus": GOLD, "exact_period": GOLD**2+GOLD+1,
                       "proper_divisor_states": gold_witnesses},
    }

if __name__ == "__main__":
    import json
    print(json.dumps(audit(), indent=2))
